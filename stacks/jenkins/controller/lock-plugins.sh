#!/usr/bin/env bash
# Regenerates plugins.lock.txt: every plugin listed in plugins.txt plus all of its dependencies,
# pinned to the exact versions jenkins-plugin-cli resolves for the Jenkins core pinned in
# versions.env (JENKINS_IMAGE). The controller image installs from the lock file only, so a
# rebuild never upgrades a plugin by surprise.
#
# Run after editing plugins.txt, or to upgrade plugins on purpose; review the diff, commit,
# then rerun the jenkins component. Needs Docker, not root.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$here/../../.." && pwd)"
image="$(sed -n 's/^JENKINS_IMAGE=//p' "$root/versions.env")"
[[ -n "$image" ]] || { echo "JENKINS_IMAGE not found in versions.env" >&2; exit 1; }

echo "resolving plugins.txt against $image" >&2
resolved="$(docker run --rm -i --entrypoint sh "$image" -c '
  cat > /tmp/plugins.txt
  if ! jenkins-plugin-cli --plugin-file /tmp/plugins.txt --plugin-download-directory /tmp/p >/tmp/cli.log 2>&1; then
    cat /tmp/cli.log >&2; exit 1
  fi
  for f in /tmp/p/*.jpi; do
    # Manifest lines wrap at 72 characters with a leading space on continuation lines.
    v="$(unzip -p "$f" META-INF/MANIFEST.MF | tr -d "\r" | awk "/^ /{l=l substr(\$0,2);next} {if(l!=\"\")print l; l=\$0} END{print l}" | sed -n "s/^Plugin-Version: //p")"
    printf "%s:%s\n" "$(basename "$f" .jpi)" "$v"
  done | sort
' < "$here/plugins.txt")"
[[ -n "$resolved" ]] || { echo "no plugin resolved" >&2; exit 1; }

{
  echo "# Generated by lock-plugins.sh for ${image}. Do not edit by hand: edit plugins.txt and rerun."
  echo "$resolved"
} > "$here/plugins.lock.txt"
echo "wrote $(echo "$resolved" | wc -l) pinned plugins to plugins.lock.txt" >&2
