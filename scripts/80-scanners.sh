#!/usr/bin/env bash
# Scanner CLIs on the host: each is a thin wrapper around the official image, pinned in versions.env.
# Developers and operators get the same versions Jenkins uses, with no curl-pipe-bash installs.
set -euo pipefail
# shellcheck source=../lib/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/../lib/common.sh"
require_root
load_env

BIN_DIR=/usr/local/bin

pull() { log "pulling $1"; docker pull --quiet "$1" >/dev/null; }

# write_wrapper <name> <image> <extra docker run args...>
write_wrapper() {
  local name="$1" image="$2"; shift 2
  local extra="$*"
  cat > "$BIN_DIR/$name" <<WRAPPER
#!/usr/bin/env bash
# Generated by devsecops-infra/scripts/80-scanners.sh. Runs $image against the current directory.
set -euo pipefail
tty_flag=""
[[ -t 0 && -t 1 ]] && tty_flag="-it"
exec docker run --rm \$tty_flag \\
  --user "\$(id -u):\$(id -g)" \\
  -e HOME=/tmp \\
  -v "\$PWD":/src -w /src \\
  $extra \\
  "$image" "\$@"
WRAPPER
  chmod 755 "$BIN_DIR/$name"
  log "installed $BIN_DIR/$name"
}

for var in TRIVY_IMAGE GITLEAKS_IMAGE SEMGREP_IMAGE SYFT_IMAGE HADOLINT_IMAGE CHECKOV_IMAGE KICS_IMAGE ZAP_IMAGE; do
  pull "$(image_for "$var")"
done

write_wrapper trivy    "$TRIVY_IMAGE"    "-v devsecops-trivy-cache:/tmp/.cache -e TRIVY_CACHE_DIR=/tmp/.cache/trivy"
write_wrapper gitleaks "$GITLEAKS_IMAGE" "-e GIT_CONFIG_COUNT=1 -e GIT_CONFIG_KEY_0=safe.directory -e GIT_CONFIG_VALUE_0=/src"
write_wrapper semgrep  "$SEMGREP_IMAGE"  "-v devsecops-semgrep-cache:/tmp/.cache"
write_wrapper syft     "$SYFT_IMAGE"     "-v devsecops-syft-cache:/tmp/.cache"
write_wrapper hadolint "$HADOLINT_IMAGE" "--entrypoint hadolint"
write_wrapper checkov  "$CHECKOV_IMAGE"  "-v devsecops-checkov-cache:/tmp/.cache"
write_wrapper kics     "$KICS_IMAGE"     ""
write_wrapper zap      "$ZAP_IMAGE"      "-v \"\$PWD\":/zap/wrk:rw"

cat <<MSG
Scanner wrappers installed. Examples, run from a project directory:
  gitleaks detect --source . --redact
  semgrep scan --config p/default --config p/php --config p/typescript
  trivy fs --scanners vuln,secret,misconfig .
  syft dir:. -o cyclonedx-json > sbom.cdx.json
  hadolint Dockerfile
  checkov -d .
  kics scan -p .
  zap zap-baseline.py -t https://staging.example.internal -r zap-report.html
Pre-commit hook: cp templates/pre-commit <repo>/.git/hooks/pre-commit
MSG
